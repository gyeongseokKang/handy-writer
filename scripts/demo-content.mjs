export function filler(chars, seed = 0) {
  const paragraphs = [];
  let total = 0;
  let i = seed;
  while (total < chars) {
    const sentences = [];
    for (let k = 0; k < 3; k++) sentences.push(POOL[(i++ * 7) % POOL.length]);
    const text = sentences.join(" ");
    paragraphs.push(text);
    total += text.length;
  }
  return paragraphs.join("\n\n");
}

